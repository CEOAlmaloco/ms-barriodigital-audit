-- Referencia Oracle (EP3-02 §9, EP3-07 §5, EP3-41). Hibernate ddl-auto: update crea/ajusta.
-- Idempotencia: uk_audit_entries_event_id sobre event_id.

CREATE TABLE audit_entries (
    id             NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    event_id       VARCHAR2(36)  NOT NULL,
    event_type     VARCHAR2(80)  NOT NULL,
    occurred_at    TIMESTAMP WITH TIME ZONE NOT NULL,
    producer       VARCHAR2(40)  NOT NULL,
    actor_id       VARCHAR2(64),
    actor_name     VARCHAR2(200),
    actor_role     VARCHAR2(40),
    source_ip      VARCHAR2(64),
    resource_type  VARCHAR2(40)  NOT NULL,
    resource_id    VARCHAR2(400) NOT NULL,
    action         VARCHAR2(40),
    before_json    CLOB,
    after_json     CLOB,
    result         VARCHAR2(40),
    summary        VARCHAR2(500),
    request_id     VARCHAR2(36),
    folio          VARCHAR2(32),
    sequence_num   NUMBER(19),
    details_json   CLOB,
    CONSTRAINT uk_audit_entries_event_id UNIQUE (event_id)
);

CREATE INDEX idx_audit_entries_occurred_at ON audit_entries (occurred_at);
CREATE INDEX idx_audit_entries_resource ON audit_entries (resource_type, resource_id);
CREATE INDEX idx_audit_entries_request ON audit_entries (request_id);
